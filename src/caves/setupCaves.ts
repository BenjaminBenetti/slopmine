/** The cave band (spawn feet Y). */
const CAVE_MIN_Y = 147
const CAVE_MAX_Y = 232

const bats: EntitySpawnConfig = {
  entityType: 'glow_bat', spawnRate: 0.12, maxNearby: 10, minY: 150, maxY: 230, maxLightLevel: 7,
  createEntity: (pos: THREE.Vector3) => new GlowBatEntity({ position: pos }),
}
const spiders = (spawnRate: number, maxNearby: number): EntitySpawnConfig => ({
  entityType: 'cave_spider', spawnRate, maxNearby, minY: CAVE_MIN_Y, maxY: CAVE_MAX_Y, maxLightLevel: 7,
  createEntity: (pos: THREE.Vector3) => new CaveSpiderEntity({ position: pos }),
})

/** Plain caves' creatures: bats, and the odd cave spider. */
const PLAIN_SPAWNS: readonly EntitySpawnConfig[] = [bats, spiders(0.02, 2)]

/** Zone strength at a spawn position from which a special zone's creatures spawn there. */
const ZONE_SPAWN_STRENGTH = 0.4

/** Each cave biome's creatures, on top of the surface biome's own cave mobs (cave slimes). */
const CAVE_SPAWNS: Readonly<Record<CaveBiomeId, readonly EntitySpawnConfig[]>> = {
  dripstone_caverns: [bats, spiders(0.03, 2)],
  mossy_grotto: [bats],
  glowworm_grotto: [bats],
  crystal_geode: [bats, {
    entityType: 'geode_crawler', spawnRate: 0.12, maxNearby: 3, minY: CAVE_MIN_Y, maxY: CAVE_MAX_Y, maxLightLevel: 7,
    createEntity: (pos: THREE.Vector3) => new GeodeCrawlerEntity({ position: pos }),
  }],
  fungal_hollow: [bats, {
    entityType: 'sporeling', spawnRate: 0.25, maxNearby: 6, minY: CAVE_MIN_Y, maxY: CAVE_MAX_Y, maxLightLevel: 9,
    createEntity: (pos: THREE.Vector3) => new SporelingEntity({ position: pos }),
  }],
  frozen_cave: [bats],
  magma_chamber: [{
    entityType: 'ember_salamander', spawnRate: 0.3, maxNearby: 4, minY: CAVE_MIN_Y, maxY: CAVE_MAX_Y,
    validGroundBlocks: [BlockIds.BASALT, BlockIds.MAGMA, BlockIds.OBSIDIAN, BlockIds.STONE, BlockIds.COLUMNAR_BASALT],
    createEntity: (pos: THREE.Vector3) => new EmberSalamanderEntity({ position: pos }),
  }],
  webbed_hollow: [bats, spiders(0.2, 4)],
}

export interface CavesDeps {
  readonly scheduler: TaskScheduler
  readonly entitySpawner: EntitySpawner
  readonly caveAtmosphere: CaveAtmosphere
  readonly seed: number
  /** Surface (layer 1) biome name at a world position (biomeRegistry region lookup). */
  getSurfaceBiome(x: number, z: number): string
}

/**
 * Caves and dark places, runtime side (the blocks are generated by the
 * worker's cave dressing, generate/caves/CaveDressing.ts):
 * - cave creatures as an EntitySpawner provider: while the player is in a
 *   cave, each spawn position's special zone brings its mobs (glow bats nearly
 *   everywhere, cave spiders, geode crawlers, sporelings, ember salamanders);
 *   plain caves get bats and the odd spider
 * - the CRITICAL 'caves' task: emits `cave-biome-entered` (journal) when the
 *   player reaches a new special cave zone.
 * The atmosphere (fog, haze, light floor) is CaveAtmosphere, driven by the
 * 'skybox' task.
 */
/**
 * Abandoned mineshaft chests (MineshaftFeature puts an ore crate beside each):
 * a miner's leftovers - torches, coal and raw ore, food, sometimes gold,
 * TNT, rope ladders, a pickaxe, celestite or a diamond.
 */
function registerMineshaftLoot(): void {
  registerChestLootTable({
    id: 'abandoned-mineshaft',
    signatureBlocks: [BlockIds.ORE_CRATE],
    signatureRadius: 3,
    roll(roll) {
      const stacks: LootStack[] = []
      const add = (id: string, min: number, max: number, salt: number): void => {
        const item = createItemFromId(id)
        if (item) stacks.push({ item, count: min + Math.floor(roll(salt) * (max - min + 1)) })
      }
      add('torch_block', 4, 10, 1)
      add('coal', 4, 9, 2)
      add('iron_ore', 2, 6, 3)
      add('copper_ore', 2, 5, 4)
      add(roll(5) < 0.5 ? 'bread' : 'baked_potato', 2, 4, 6)
      if (roll(7) < 0.4) add('gold_ore', 1, 3, 8)
      if (roll(9) < 0.3) add('tnt_block', 1, 2, 10)
      if (roll(11) < 0.35) add('rope_ladder_block', 3, 8, 12)
      if (roll(13) < 0.35) add('celestite_shard', 2, 5, 14)
      if (roll(15) < 0.15) add('iron_pickaxe', 1, 1, 16)
      if (roll(17) < 0.15) add('diamond', 1, 2, 18)
      return stacks
    },
  })
}

export function setupCaves(deps: CavesDeps): void {
  registerMineshaftLoot()

  const sample: CaveBiomeSample = { biome: null, strength: 0 }
  deps.entitySpawner.addSpawnProvider((_biome, layer, position) => {
    if (layer !== 1 || deps.caveAtmosphere.factor < 0.5) return undefined
    caveBiomeAt(position.x, position.z, deps.seed, deps.getSurfaceBiome, sample)
    return sample.biome && sample.strength >= ZONE_SPAWN_STRENGTH ? CAVE_SPAWNS[sample.biome] : PLAIN_SPAWNS
  })

  let last: CaveBiomeId | null = null
  let timer = 0
  const result = { completed: true, elapsedMs: 0, workUnits: 0 }
  deps.scheduler.registerTask({
    id: 'caves',
    priority: TaskPriority.CRITICAL,
    enabled: true,
    execute(dt: number) {
      timer += dt
      if (timer < 0.5) return result
      timer = 0
      const biome = deps.caveAtmosphere.biome
      if (biome && biome !== last) gameEvents.emit({ type: 'cave-biome-entered', caveBiome: biome })
      if (biome) last = biome
      return result
    },
  })
}
